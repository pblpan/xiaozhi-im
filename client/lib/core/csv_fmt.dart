/// CSV 落盘的几个**纯函数**（扫码枪与盘点共用）。
///
/// ── 为什么要单独一个文件 ──────────────────────────────────────
/// 转义和条码单元格这两个东西，两个模块各写了一份（一模一样）。
/// 复制的代价不是"多几行"，而是**修一处漏一处**：
/// 条码在 Excel 里变科学计数法这种问题，只改扫码枪那份的话，
/// 盘点导出的差异表照样是坏的，而且没人会想到去那边查。
library;

/// CSV 转义：含逗号/引号/换行就加引号，内部引号翻倍。
/// 商品名里带逗号（"苹果,红富士"）不转义会直接把列冲掉。
String csvEsc(Object? v) {
  final s = (v ?? '').toString();
  if (s.contains(',') || s.contains('"') || s.contains('\n') ||
      s.contains('\r')) {
    return '"${s.replaceAll('"', '""')}"';
  }
  return s;
}

/// 条码列的取值：**长数字条码必须写成 Excel 认得的文本**。
///
/// ── 龙哥 2026-09-19 报的"条码栏是乱码"，根因是这个 ──────────────
/// CSV 里没有任何"单元格格式"这回事，Excel/WPS 打开时会自己猜类型。
/// 13 位的 EAN-13 条码（如 `6921817824327`）被猜成**数值**，于是：
///   · 超过 11 位 → 显示成科学计数法 `6.92182E+12`（看着就是"乱码"）
///   · 超过 15 位 → 末尾数字被**直接置零**（双精度只有 ~15 位有效位）
/// 条码是最不能出错的一列：位数变短、末尾变 0，回头一条都对不上账。
///
/// ── 为什么用 `="..."` 而不是别的办法 ──────────────────────────
/// 打开 CSV 时 Excel / WPS / LibreOffice / Google Sheets 都会把以 `=` 开头的
/// 单元格当公式求值，`="6921817824327"` 的求值结果就是**文本**
/// `6921817824327` —— 原样显示，不会变形。
/// 这是各平台通行的写法，不用换扩展名、也不用引额外的库。
///
/// ⚠️ 副作用（认了，也值得）：拿这份 CSV 做程序化导入时读到的会是
/// `="..."` 这个公式串，得先剥掉。取舍是"给人看 > 给机器看" ——
/// 给机器的那份本来就该走接口，不该靠 CSV 传。
///
/// 只对"纯数字且 ≥ 11 位"的条码加保护：
///   · 短数字（内部码 123）加了反而平白变成公式，没必要；
///   · 含字母的条码 Excel 本来就不会当数值，不用管。
///
/// 返回的串**还要再过一遍 [csvEsc]**（里面含引号）—— 调用顺序别反。
String barcodeCsvCell(Object? v) {
  final s = (v ?? '').toString();
  if (s.length >= 11 && RegExp(r'^\d+$').hasMatch(s)) return '="$s"';
  return s;
}

/// 扫码去重判据。
///
/// ── 为什么单独抽一个文件出来 ────────────────────────────────────
/// 这是整个摄像头扫码里**最容易做错、错了又不报错**的一段逻辑：
/// 判错的结果是"件数少算了"或者"件数多算了"，界面上没有任何异常，
/// 只有盘完对账才发现对不上。
///
/// 而它偏偏又最难测 —— 在页面里它是 `State` 的一个私有方法，
/// 要测就得把 `mobile_scanner` 的插件、相机通道全拉起来。
/// 所以把**判据**抽成这个纯函数：不依赖 Flutter、不依赖插件，
/// 可以拿一串 (码, 时间) 序列直接断言行为。
///
/// ── 判据本身 ────────────────────────────────────────────────────
/// `mobile_scanner` 自带的 `DetectionSpeed` 只有两档能选，而**两档都不能用**：
///
///   · `noDuplicates` —— 官方语义是「同一个条码只会被扫到一次，
///     **直到扫到另一个条码之前都不会再报**」。
///     而盘点最常见的动作就是**连扫同一个商品的第 2 件、第 3 件**，
///     用它会把这些件数**静默丢掉**（界面毫无反应，员工以为坏了）。
///
///   · `normal` / `unrestricted` —— 按检测超时反复上报同一个码。
///     相机对着一个条码多停半秒就会重复计很多次 → **件数虚高**。
///
/// 所以正确做法是：用 `normal` 拿到"能重复上报"的能力，
/// 再**自己按 (码, 时间) 判断**这一次上报算不算数 —— 就是下面这个函数。
library;

/// 同一个码在这么长时间内的重复上报，视为"相机还对着同一件"，不重复计。
///
/// 取值权衡：
/// · 太短 → 相机对着一件多停一会儿就被重复计，盘出来虚高；
/// · 太长 → 连扫两件同样的货，第二件被吞掉，盘出来偏少。
///
/// 取 1200ms（偏"不虚高"那一侧）：多计出来的盘盈要人一条条去核，
/// 少一件好歹只是在盈亏表上显示为盘亏，员工当场还能发现再补扫。
///
/// ⚠️ **已知限制（相机扫码的固有缺陷，不是能靠调参消掉的）**：
/// 相机**没有办法区分**"同一个条码还对着画面没动"和"拿走了、又换了一件同款"——
/// 这两件事在识别结果上看起来完全一样（同一个码、画面里还有它）。
/// 所以只要对着同一个条码**超过这个冷却时间不动**，它就会被**再算一次**。
/// 现场表现就是"手机放着没动，数字自己往上涨"。
///
/// 缓解手段（都在界面上，不在这段逻辑里）：
///   1. 扫中时取景框**闪绿**——让员工形成"闪了就移开"的条件反射；
///   2. 「再记 1 件」按钮 —— 要给同一件加数量就用它，不靠手感；
///   3. 提示文案直接写"同一个条码连续对着不会重复计数"。
///
/// 如果以后现场反馈虚高得厉害，正确的修法是**不要只比条码**：
/// 连条码在画面里的**位置**一起比（`Barcode.boundingBox`）——位置基本没动 = 还是同一件。
/// 但那引入"手抖被当成新件"的反向风险，需要真机调阈值，所以这一版没上。
const int kSameCodeCooldownMs = 1200;

/// 这一次识别结果要不要计入。
///
/// [lastCode] 上一次**被接受**的条码（从未接受过传 null）；
/// [lastAcceptAt] 上一次被接受的时间戳（毫秒）。
///
/// 规则：
///   · 和上次**不同**的码 → 立刻接受（不受冷却影响，换货就该马上进）
///   · 和上次**相同**的码、且在冷却窗口内 → 忽略（相机还对着同一件）
///   · 和上次**相同**的码、但已过冷却窗口 → 接受（这就是第二件、第三件）
bool shouldAcceptScan({
  required String code,
  required String? lastCode,
  required int lastAcceptAt,
  required int now,
  int cooldownMs = kSameCodeCooldownMs,
}) {
  if (code.isEmpty) return false;
  if (lastCode == null || code != lastCode) return true;
  return (now - lastAcceptAt) >= cooldownMs;
}

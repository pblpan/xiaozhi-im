/// 摄像头扫码页与**业务层之间唯一的接口**。
///
/// ── 为什么要这一层 ──────────────────────────────────────────────
/// 扫码枪（stocktake）和盘点（inventory）用的是**同一个相机页**：
/// 同一套去重判据、同一套写入闸门、同一种"闪绿"反馈。
/// 那 400 行里最值钱也最容易做错的正是这些机制 —— 抄第二份就等于
/// 给「连扫同款件数被静默丢掉」「相机的码反复上报把件数算虚高」
/// 这类**不报错的 bug** 各留一条复活的路。
///
/// 所以相机页不认识任何一个仓库，它只认这个接口：
/// "把扫到的这个码落下去，并告诉我该给员工看什么"。
/// 具体是扫码枪的 `addScan` 还是盘点的阶段化 `scan`，由各自实现决定。
///
/// 这一层抽出来还有个副作用好处：**相机页可以脱离 mobile_scanner 测试** ——
/// 拿一个假 sink 就能验"同一码两次上报只算一件"。
library;

/// 落一笔的结果，直接就是员工在扫码页底部要看到的东西。
class ScanFeedback {
  const ScanFeedback({
    required this.accepted,
    this.message,
    this.hit,
  });

  /// 这一笔有没有真的写进去。
  ///
  /// 🔴 必须与"界面反馈"分开：被拒绝的扫码**不能闪绿**。
  ///    闪绿是"成功"的条件反射训练，给一次拒绝闪绿，
  ///    员工会养成"闪了就是进去了"的错觉，而实际上那条根本没记上。
  final bool accepted;

  /// 给员工看的一句话（判定的原因）。null = 不用多说。
  final String? message;

  /// 刚扫到的那一行（`barcode` / `name` / `unit` / `qty` …），用于底部回显。
  /// 被拒绝时通常是 null（界面显示的是"没记上"，不是"记了多少"）。
  final Map<String, dynamic>? hit;
}

/// 采集终点：把"扫到了一个码"落到某个业务上。
abstract class ScanSink {
  /// 落一笔。[sheetNo] 是当前单据。
  ///
  /// 实现方**不允许抛异常来表示业务拒绝**（比如"该商品不属于本盘点位"）——
  /// 那是正常的判定结果，走 [ScanFeedback.accepted]。
  /// 抛异常只留给真正的故障（数据库写不进去）。
  Future<ScanFeedback> record(String sheetNo, String code);

  /// 当前单据的小结，页面底部显示。
  ///
  /// 约定的键（缺了就当 0，不要报错 —— 两个模块要的数字本来就不一样）：
  ///   · `total_qty` 合计数量
  ///   · `kinds`     品种数
  Future<Map<String, dynamic>> summary(String sheetNo);

  /// 最近扫到的几条（**新的在前**），信息区列表用。
  ///
  /// ── 为什么要列表而不只是一行"刚扫了什么" ────────────────────────
  /// 只显示最后一笔的话，员工发现"刚才那件好像扫重了"时**没法回头查** ——
  /// 得退出扫码页、回到列表页翻。而那正是他需要当场确认的时刻。
  /// 信息区占屏幕一大半的意义就在能一眼看到前面几笔，扫错了立刻发现。
  ///
  /// 返回空列表 = 这个业务不提供明细，信息区就不显示列表。
  Future<List<Map<String, dynamic>>> recent(String sheetNo, {int limit = 40});
}

/** 关键词检索：返回按得分降序的命中（最多 max 条）。无命中返回 [] */
function search(question, max = 3) {
  const q = String(question || '').trim();
  if (!q) return [];
  // 把问题拆成"词面"：整句 + 去掉常见停用词后的 2 字以上片段
  const segs = [q, ...q.replace(/[?？!！。，,、的怎么什么为什么啊吧呢是能可以吗]/g, ' ')
    .split(/\s+/).filter((s) => s.length >= 2)];
  const scored = [];
  for (const e of ENTRIES) {
    let score = 0;
    for (const kw of e.kw) {
      if (q.includes(kw)) score += kw.length >= 3 ? 3 : 2;
    }
    // 标题整串命中（问题几乎原文）直接满分
    if (e.q.includes(q) || q.includes(e.q.replace(/[？?]/g, ''))) score += 6;
    for (const s of segs) {
      if (s.length >= 2 && e.q.includes(s)) score += 1;
    }
    if (score > 0) scored.push({ score, ...e });
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, max).map(({ score, ...e }) => e);
}

module.exports = { ENTRIES, search };
